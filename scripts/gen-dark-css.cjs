// Generates src/dark.css: dark-mode overrides for the status/brand tint classes actually used in src/.
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'src');

const FAMILIES = {
  red:    { rgb: '239 68 68',   c200: '#fecaca', c300: '#fca5a5', c400: '#f87171' },
  green:  { rgb: '34 197 94',   c200: '#bbf7d0', c300: '#86efac', c400: '#4ade80' },
  amber:  { rgb: '245 158 11',  c200: '#fde68a', c300: '#fcd34d', c400: '#fbbf24' },
  yellow: { rgb: '234 179 8',   c200: '#fef08a', c300: '#fde047', c400: '#facc15' },
  orange: { rgb: '249 115 22',  c200: '#fed7aa', c300: '#fdba74', c400: '#fb923c' },
  blue:   { rgb: '59 130 246',  c200: '#bfdbfe', c300: '#93c5fd', c400: '#60a5fa' },
  teal:   { rgb: '20 184 166',  c200: '#99f6e4', c300: '#5eead4', c400: '#2dd4bf' },
  purple: { rgb: '168 85 247',  c200: '#e9d5ff', c300: '#d8b4fe', c400: '#c084fc' },
  brand:  { rgb: '59 130 246',  c200: '#bfdbfe', c300: '#93c5fd', c400: '#60a5fa' },
};

function walk(dir, out = []) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, f.name);
    if (f.isDirectory()) walk(p, out);
    else if (/\.(jsx?|html)$/.test(f.name)) out.push(p);
  }
  return out;
}

const families = Object.keys(FAMILIES).join('|');
const re = new RegExp(`(?:hover:)?(?:bg|text|border)-(?:${families})-(?:50|100|200|300|600|700|800|900)\\b`, 'g');
const found = new Set();
for (const file of walk(SRC)) {
  for (const m of fs.readFileSync(file, 'utf8').matchAll(re)) found.add(m[0]);
}

const alpha = { 50: 0.14, 100: 0.22, 200: 0.3 };
const borderAlpha = { 50: 0.25, 100: 0.3, 200: 0.35, 300: 0.45, 600: 1, 700: 1 };
const textShade = { 600: 'c400', 700: 'c300', 800: 'c200', 900: 'c200', 300: 'c300', 200: 'c200' };

const esc = (cls) => cls.replace(/:/g, '\\:');
const rules = [];

for (const cls of [...found].sort()) {
  const hover = cls.startsWith('hover:');
  const base = hover ? cls.slice(6) : cls;
  const [, kind, fam, shade] = base.match(/^(bg|text|border)-([a-z]+)-(\d+)$/);
  const f = FAMILIES[fam];
  const sel = `.dark .${esc(cls)}${hover ? ':hover' : ''}`;
  let decl = null;

  if (kind === 'bg') {
    if (alpha[shade] !== undefined) decl = `background-color: rgb(${f.rgb} / ${hover ? alpha[shade] + 0.08 : alpha[shade]});`;
    // solid fills (600+) stay as they are
  } else if (kind === 'border') {
    if (['50', '100', '200', '300'].includes(shade)) decl = `border-color: rgb(${f.rgb} / ${borderAlpha[shade]});`;
  } else if (kind === 'text') {
    const key = textShade[shade];
    if (key) decl = `color: ${f[key]};`;
  }
  if (decl) rules.push(`${sel} { ${decl} }`);
}

const header = `/* GENERATED by scripts/gen-dark-css.cjs (run: node scripts/gen-dark-css.cjs) from the classes used in src/. Dark-mode overrides for
 * the status and brand tint classes (light pastel fills become translucent tints, dark text
 * becomes light). Solid fills and white-on-color text are intentionally left alone.
 * Regenerate if a new tint class is introduced. */\n`;
fs.writeFileSync(path.join(SRC, 'dark.css'), header + rules.join('\n') + '\n');
console.log(`${found.size} classes scanned, ${rules.length} dark rules written`);
